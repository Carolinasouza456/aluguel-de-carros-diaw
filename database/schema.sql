-- esquema do banco para o supabase (postgresql)
-- rode este arquivo no sql editor do supabase antes de subir o back-end

create table usuario (
    id bigint generated by default as identity primary key,
    login varchar(50) not null unique,
    senha varchar(255) not null,
    perfil varchar(20) not null check (perfil in ('CLIENTE', 'EMPRESA', 'BANCO'))
);

create table cliente (
    id bigint generated by default as identity primary key,
    rg varchar(20) not null,
    cpf varchar(14) not null unique,
    nome varchar(120) not null,
    endereco varchar(255) not null,
    profissao varchar(100),
    usuario_id bigint not null unique references usuario (id)
);

create table rendimento (
    id bigint generated by default as identity primary key,
    entidade_empregadora varchar(120) not null,
    valor numeric(12, 2) not null check (valor >= 0),
    cliente_id bigint not null references cliente (id) on delete cascade
);

create table agente (
    id bigint generated by default as identity primary key,
    nome varchar(120) not null,
    usuario_id bigint not null unique references usuario (id)
);

create table automovel (
    id bigint generated by default as identity primary key,
    matricula varchar(30) not null unique,
    ano integer not null,
    marca varchar(50) not null,
    modelo varchar(50) not null,
    placa varchar(10) not null unique
);

create table pedido (
    id bigint generated by default as identity primary key,
    cliente_id bigint not null references cliente (id),
    automovel_id bigint not null references automovel (id),
    data_inicio date not null,
    data_fim date not null,
    status varchar(20) not null
        check (status in ('EM_ANALISE', 'APROVADO', 'REPROVADO', 'CANCELADO', 'CONTRATADO')),
    parecer varchar(500),
    agente_avaliador_id bigint references agente (id),
    data_criacao timestamp not null,
    check (data_fim >= data_inicio)
);

create table contrato (
    id bigint generated by default as identity primary key,
    pedido_id bigint not null unique references pedido (id) on delete cascade,
    tipo_proprietario varchar(20) not null check (tipo_proprietario in ('CLIENTE', 'EMPRESA', 'BANCO')),
    data_contrato date not null
);

create table contrato_credito (
    id bigint generated by default as identity primary key,
    contrato_id bigint not null unique references contrato (id) on delete cascade,
    banco_id bigint not null references agente (id),
    valor numeric(12, 2) not null check (valor > 0),
    parcelas integer not null check (parcelas >= 1)
);

create index idx_pedido_cliente on pedido (cliente_id);
create index idx_pedido_status on pedido (status);

-- o supabase expoe as tabelas do schema public por uma api propria (postgrest).
-- como o acesso aqui e so pelo spring boot, ligamos o rls sem politicas para
-- bloquear qualquer acesso externo (o spring usa o usuario postgres, que ignora o rls)
alter table usuario enable row level security;
alter table cliente enable row level security;
alter table rendimento enable row level security;
alter table agente enable row level security;
alter table automovel enable row level security;
alter table pedido enable row level security;
alter table contrato enable row level security;
alter table contrato_credito enable row level security;
